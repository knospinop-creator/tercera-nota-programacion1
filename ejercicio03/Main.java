// Ejercicio 3: Arquitectura multicapa (teoría)
//
// Completar las frases:
// 1. La capa de PRESENTACIÓN se encarga de la interfaz y la interacción con el usuario.
// 2. La capa de LÓGICA DE NEGOCIO contiene las reglas del sistema.
// 3. La capa de ACCESO A DATOS se comunica con la base de datos.
//
// Ventaja de separar el programa en capas:
// Cada capa tiene una sola función, así que se puede modificar o mejorar
// una sin dañar las demás. Esto hace el programa más fácil de mantener,
// reutilizar y hacer crecer.

public class Main {
    public static void main(String[] args) {
        System.out.println("1. Capa de PRESENTACIÓN: interfaz e interacción con el usuario.");
        System.out.println("2. Capa de LÓGICA DE NEGOCIO: reglas del sistema.");
        System.out.println("3. Capa de ACCESO A DATOS: comunicación con la base de datos.");
        System.out.println();
        System.out.println("Ventaja: cada capa se puede cambiar sin afectar las otras,");
        System.out.println("lo que facilita el mantenimiento, la reutilización y el crecimiento.");
    }
}
